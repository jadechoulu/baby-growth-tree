test('会认与会写独立按单字去重，支持批量和扩展汉字；撤回不影响另一能力',()=>{
 const draft=characterDraft('大大小，小A123！\n𠮷',{});
 assert.deepEqual(draft.characters,['大','小','𠮷']);
 const document=patchDocument(empty(),{records:draft.changes});
 assert.deepEqual(characterSummary(document.records),{recognized:3,written:0});
 assert.equal(Object.keys(characterDraft('大小',document.records).changes).length,0);
 const review=patchDocument(document,{records:characterDraft('大',document.records,'writing').changes});
 assert.deepEqual(characterSummary(review.records),{recognized:3,written:1});
 const removed=patchDocument(review,{records:{[characterKey('小')]:{status:'paused'}}});
 assert.equal(characterSummary(removed.records).recognized,2);
 assert.deepEqual(characterSummary(mergeBackup(empty(),removed).value.records),{recognized:2,written:1});
 const both=patchDocument(removed,{records:characterDraft('大小',removed.records,'both').changes});
 assert.deepEqual(characterSummary(both.records),{recognized:3,written:2});
 assert.equal(Object.keys(characterDraft('ABC 12',{}).changes).length,0);
 assert.throws(()=>characterKey('大小'));
 assert.throws(()=>validateBackup({...empty(),records:{'hanzi:v1:abc':{status:'done'}}}));
 const newer=patchDocument(document,{records:{[characterKey('大')]:{status:'using'}}});
 assert.throws(()=>patchDocument(newer,{records:{[characterKey('大')]:{status:'done'}}},document),/其他页面/);
});
