const wb = XLSX.utils.book_new();
for (const section of sections) {
 const ws = XLSX.utils.aoa_to_sheet(section.rows);
 ws['!cols'] = [{wch: 20}, {wch: 80}];
 if (section.rows[0] && section.rows[0].length > 2) {
  ws['!cols'] = section.rows[0].map((_, i) => ({ wch: i === 0 ? 18 : 30 }));
 }
 XLSX.utils.book_append_sheet(wb, ws, section.title.slice(0, 31));
}

const outPath = join(root, 'curriculum', 'plan.xlsx');
mkdirSync(dirname(outPath), { recursive: true });
XLSX.writeFile(wb, outPath);
console.log('已生成 Excel 文件：' + outPath);
